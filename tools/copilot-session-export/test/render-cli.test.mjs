// node --test tools/copilot-session-export/test/render-cli.test.mjs
// 合成したイベント列で、Copilot CLI の /export file と同じ組み立てになることを確かめる。
// 期待値の書式は、実際の CLI(1.0.100)の /export の出力と突き合わせて決めたもの。
import assert from "node:assert/strict";
import { test } from "node:test";
import { buildTimeline, cliOutputPath, parseExportArgs, renderCliExport } from "../session-export/render-cli.mjs";
import { isAbsolute, join, resolve } from "node:path";

const cwd = "/work/repo";
const t = (s) => new Date(Date.UTC(2026, 9, 22, 0, 0, s)).toISOString();
let n = 0;
const ev = (type, data, s, extra = {}) => ({ type, data, id: String(++n), timestamp: t(s), ...extra });
const events = [
  ev("session.start", { sessionId: "sid-1", startTime: t(0), context: { cwd } }, 0),
  ev("user.message", { content: "README を読んで <b> を説明して" }, 1),
  ev("user.message", { content: "<system_reminder>自動</system_reminder>", source: "instruction-discovery" }, 1),
  ev("assistant.message", { messageId: "m1", content: "", reasoningText: "まず読む", toolRequests: [{ toolCallId: "c1", name: "view", intentionSummary: "view the file", arguments: { path: `${cwd}/README.md`, view_range: [1, -1] } }] }, 2),
  ev("tool.execution_complete", { toolCallId: "c1", success: true, result: { content: "# title" } }, 3),
  ev("assistant.message", { messageId: "m2", content: "", toolRequests: [{ toolCallId: "c2", name: "task", toolTitle: "Explore code", arguments: { prompt: "調べて" } }] }, 4),
  ev("assistant.message", { messageId: "s1", content: "途中", reasoningText: "委譲先の推論", parentToolCallId: "c2", toolRequests: [{ toolCallId: "c3", name: "grep", arguments: { pattern: "foo", path: cwd } }] }, 5, { agentId: "a1" }),
  ev("tool.execution_complete", { toolCallId: "c3", success: false, error: { message: "denied" }, parentToolCallId: "c2" }, 6, { agentId: "a1" }),
  ev("tool.execution_complete", { toolCallId: "c2", success: true, result: { content: "報告" } }, 7),
  ev("assistant.message", { messageId: "m3", content: "`<b>` は太字です。<br> も" }, 8),
  ev("session.info", { message: "書き出した", infoType: "file_created" }, 9),
  ev("session.info", { message: "情報" }, 9),
];

test("タイムライン: 人の依頼・本体の推論・ツール・委譲のまとまりだけを拾う", () => {
  const kinds = buildTimeline(events).map((x) => x.k);
  assert.deepEqual(kinds, ["user", "reasoning", "tool", "group", "copilot", "info"]);
  const g = buildTimeline(events)[3];
  assert.deepEqual(g.children.map((c) => c.k), ["copilot", "tool"]); // 委譲先の推論は出さない
});

